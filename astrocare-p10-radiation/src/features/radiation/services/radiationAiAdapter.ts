import {
  RadiationMeasurement,
  RadiationTrendAnalytics,
  RadiationAlert,
  RadiationResearchStudy,
  HrpEvidenceReference,
} from '../types/radiationTypes';

/**
 * Structured radiation context payload engineered for future Gemini AI consumption (Prompt 13).
 * Strictly enforces clear boundaries between simulated telemetry, real NASA telemetry, and scientific literature.
 */
export interface RadiationAiContextPayload {
  astronautId: string;
  missionId: string;
  timestamp: string;
  simulatedTelemetry: {
    currentFluxUsVh: number;
    cumulativeDoseMsv: number;
    solarParticleEventActive: boolean;
    isSimulated: true;
    provenanceTag: 'VIRTUAL_SIMULATION_SENSOR';
  };
  nasaRadLabReference: {
    latestMeasurement: RadiationMeasurement | null;
    dataSource: 'NASA_RADLAB_REPOSITORY';
    instrumentAttribution: string;
    spacecraft: string;
    isLiveFeed: boolean;
    provenanceTag: 'HISTORICAL_NASA_TELEMETRY';
  };
  analyticsSummary: RadiationTrendAnalytics;
  activeRadiationAlerts: RadiationAlert[];
  nasaGroundingLiterature: {
    relevantOsdrStudies: Array<{
      accessionNumber: string;
      title: string;
      category: string;
      url: string;
    }>;
    hrpEvidenceReferences: Array<{
      title: string;
      riskCategory: string;
      keyFindings: string[];
      sourceUrl: string;
    }>;
    provenanceTag: 'AUTHORITATIVE_NASA_RESEARCH';
  };
  scientificIntegrityGuardrails: {
    disclaimer: string;
    personalMedicalTelemetryBoundary: string;
    simulationBoundary: string;
  };
}

export function exportRadiationContextForAI(params: {
  astronautId: string;
  missionId: string;
  currentFluxUsVh: number;
  cumulativeDoseMsv: number;
  isSpeActive: boolean;
  latestRadLabReading: RadiationMeasurement | null;
  isRadLabLive: boolean;
  trends: RadiationTrendAnalytics;
  alerts: RadiationAlert[];
  studies: RadiationResearchStudy[];
  evidence: HrpEvidenceReference[];
}): RadiationAiContextPayload {
  return {
    astronautId: params.astronautId,
    missionId: params.missionId,
    timestamp: new Date().toISOString(),
    simulatedTelemetry: {
      currentFluxUsVh: params.currentFluxUsVh,
      cumulativeDoseMsv: params.cumulativeDoseMsv,
      solarParticleEventActive: params.isSpeActive,
      isSimulated: true,
      provenanceTag: 'VIRTUAL_SIMULATION_SENSOR',
    },
    nasaRadLabReference: {
      latestMeasurement: params.latestRadLabReading,
      dataSource: 'NASA_RADLAB_REPOSITORY',
      instrumentAttribution: params.latestRadLabReading
        ? `${params.latestRadLabReading.instrument} (${params.latestRadLabReading.instrumentId})`
        : 'NASA Multi-Agency Dosimeter Repository',
      spacecraft: params.latestRadLabReading?.spacecraft || 'ISS',
      isLiveFeed: params.isRadLabLive,
      provenanceTag: 'HISTORICAL_NASA_TELEMETRY',
    },
    analyticsSummary: params.trends,
    activeRadiationAlerts: params.alerts,
    nasaGroundingLiterature: {
      relevantOsdrStudies: params.studies.slice(0, 5).map((s) => ({
        accessionNumber: s.accessionNumber,
        title: s.title,
        category: s.researchCategory,
        url: s.sourceUrl,
      })),
      hrpEvidenceReferences: params.evidence.slice(0, 3).map((e) => ({
        title: e.title,
        riskCategory: e.riskCategory,
        keyFindings: e.keyFindings,
        sourceUrl: e.url,
      })),
      provenanceTag: 'AUTHORITATIVE_NASA_RESEARCH',
    },
    scientificIntegrityGuardrails: {
      disclaimer:
        'This payload contains research information and software simulation telemetry. It does not constitute certified clinical radiation dosimetry.',
      personalMedicalTelemetryBoundary:
        'NASA RadLab records reflect vehicle environmental dosimeters from historical missions (e.g. ISS) and MUST NOT be treated as personal clinical dosimetry of the simulated crew.',
      simulationBoundary:
        'Active telemetry packets are generated by AstroCare mathematical simulation engine with isSimulated = true.',
    },
  };
}
