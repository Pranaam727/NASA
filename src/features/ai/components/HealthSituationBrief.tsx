import React from 'react';
import { DossierCard } from '@/components/common/DossierCard';
import { HealthSituationBrief as IHealthSituationBrief, TimeRangeOption } from '../types/aiTypes';
import { Activity, FileCheck, Layers } from 'lucide-react';

interface HealthSituationBriefProps {
  brief: IHealthSituationBrief | null;
  timeRange: TimeRangeOption;
  onTimeRangeChange?: (range: TimeRangeOption) => void;
  isLoading?: boolean;
}

export const HealthSituationBrief: React.FC<HealthSituationBriefProps> = ({
  brief,
  timeRange,
  onTimeRangeChange,
  isLoading,
}) => {
  if (isLoading || !brief) {
    return (
      <div className="animate-pulse space-y-4">
        <div className="h-32 bg-astro-bg-surface border border-astro-border-hairline rounded-sm" />
        <div className="h-48 bg-astro-bg-surface border border-astro-border-hairline rounded-sm" />
      </div>
    );
  }

  const isFallback = brief.providerMode === 'DETERMINISTIC_FALLBACK';

  return (
    <div className="space-y-6">
      <DossierCard
        title="HEALTH SITUATION BRIEF"
        subtitle={`ANALYTICAL TIME HORIZON: ${brief.timeRange} | MONITORED: ${brief.astronautName}`}
        action={
          <div className="flex items-center space-x-2">
            {onTimeRangeChange && (
              <div className="flex space-x-1 font-mono text-[10px]">
                {(['1H', '6H', '24H', '7D'] as TimeRangeOption[]).map((r) => (
                  <button
                    key={r}
                    onClick={() => onTimeRangeChange(r)}
                    className={`px-2 py-0.5 rounded-sm border ${
                      timeRange === r
                        ? 'bg-astro-sage/20 border-astro-sage text-astro-text-primary font-bold'
                        : 'border-astro-border-hairline text-astro-text-secondary hover:bg-astro-bg-subtle'
                    }`}
                  >
                    {r}
                  </button>
                ))}
              </div>
            )}
            <span
              className={`font-mono text-[9px] px-2 py-0.5 rounded-sm border uppercase font-bold ${
                isFallback
                  ? 'bg-[#B89A58]/15 text-[#7A6643] border-[#B89A58]/40'
                  : 'bg-astro-status-healthy/15 text-astro-status-healthy border-astro-status-healthy/40'
              }`}
            >
              {isFallback ? 'DETERMINISTIC FALLBACK — NOT GENERATED BY GEMINI' : 'GEMINI PROXY GROUNDED'}
            </span>
          </div>
        }
      >
        <div className="space-y-5">
          {/* Executive Summary Callout */}
          <div className="p-3.5 bg-astro-bg-subtle/50 border border-astro-border-hairline rounded-sm">
            <div className="font-mono text-[10px] uppercase text-astro-text-secondary mb-1">
              Executive Clinical Synthesis
            </div>
            <p className="font-body text-xs text-astro-text-primary leading-relaxed">
              {brief.executiveSummary}
            </p>
          </div>

          {/* Observations and Baselines */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="space-y-2">
              <div className="font-mono text-xs uppercase text-astro-text-secondary flex items-center space-x-1.5">
                <Activity className="w-3.5 h-3.5 text-astro-sage" />
                <span>Primary Telemetry Observations</span>
              </div>
              <ul className="space-y-1.5">
                {brief.telemetryObservations.map((obs, idx) => (
                  <li
                    key={idx}
                    className="text-xs font-body text-astro-text-secondary bg-astro-bg-surface p-2 rounded-sm border border-astro-border-hairline"
                  >
                    {obs}
                  </li>
                ))}
              </ul>
            </div>

            <div className="space-y-2">
              <div className="font-mono text-xs uppercase text-astro-text-secondary flex items-center space-x-1.5">
                <Layers className="w-3.5 h-3.5 text-astro-blue" />
                <span>Baseline Discrepancy Matrix</span>
              </div>
              <ul className="space-y-1.5">
                {brief.baselineComparisons.map((comp, idx) => (
                  <li
                    key={idx}
                    className="text-xs font-body text-astro-text-secondary bg-astro-bg-surface p-2 rounded-sm border border-astro-border-hairline"
                  >
                    {comp}
                  </li>
                ))}
              </ul>
            </div>
          </div>

          {/* Actionable Recommendations */}
          <div className="space-y-2 pt-2 border-t border-astro-border-hairline">
            <div className="font-mono text-xs uppercase text-astro-text-secondary flex items-center space-x-1.5">
              <FileCheck className="w-3.5 h-3.5 text-astro-status-healthy" />
              <span>Recommended Surveillance Protocols</span>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {brief.recommendedObservations.map((rec, idx) => (
                <div
                  key={idx}
                  className="p-2.5 bg-astro-bg-surface border border-astro-border-hairline rounded-sm text-xs font-body text-astro-text-primary"
                >
                  <span className="font-mono text-[10px] text-astro-sage font-bold block mb-1">
                    PROTOCOL {idx + 1}
                  </span>
                  {rec}
                </div>
              ))}
            </div>
          </div>
        </div>
      </DossierCard>
    </div>
  );
};
