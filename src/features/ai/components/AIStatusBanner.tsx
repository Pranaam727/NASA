import React from 'react';
import { AISystemOverview, AIProviderMode } from '../types/aiTypes';
import { Sparkles, Shield, Cpu, RefreshCw } from 'lucide-react';

interface AIStatusBannerProps {
  overview: AISystemOverview;
  onModeChange: (mode: AIProviderMode) => void;
  onRefresh: () => void;
  isLoading?: boolean;
  className?: string;
}

export const AIStatusBanner: React.FC<AIStatusBannerProps> = ({
  overview,
  onModeChange,
  onRefresh,
  isLoading = false,
  className = '',
}) => {
  const isFallback = overview.currentMode === 'DETERMINISTIC_FALLBACK';

  return (
    <div
      className={`p-3.5 bg-astro-bg-surface border border-astro-border-hairline rounded-sm space-y-3 ${className}`}
    >
      <div className="flex flex-wrap items-center justify-between gap-3">
        {/* Left: Mode & Status */}
        <div className="flex flex-wrap items-center gap-2">
          {isFallback ? (
            <span className="font-mono text-[10px] font-bold px-2.5 py-1 rounded-sm bg-[#B89A58]/15 text-[#7A6643] border border-[#B89A58]/40 flex items-center space-x-1.5">
              <Shield className="w-3.5 h-3.5 text-[#7A6643]" />
              <span>DETERMINISTIC FALLBACK — NOT GENERATED BY GEMINI</span>
            </span>
          ) : (
            <span className="font-mono text-[10px] font-bold px-2.5 py-1 rounded-sm bg-astro-status-healthy/15 text-astro-status-healthy border border-astro-status-healthy/40 flex items-center space-x-1.5">
              <Sparkles className="w-3.5 h-3.5" />
              <span>GOOGLE GEMINI 1.5 PROXY ACTIVE</span>
            </span>
          )}

          <span className="font-mono text-[10px] px-2 py-0.5 rounded-sm bg-astro-bg-subtle text-astro-text-secondary border border-astro-border-hairline flex items-center space-x-1">
            <Cpu className="w-3 h-3 text-astro-sage" />
            <span>MODEL: {overview.modelIdentifier}</span>
          </span>

          <span className="font-mono text-[10px] px-2 py-0.5 rounded-sm bg-astro-bg-subtle text-astro-text-secondary border border-astro-border-hairline">
            DATA: {overview.dataProvenance}
          </span>
        </div>

        {/* Right: Mode Switcher & Refresh Button */}
        <div className="flex items-center space-x-2">
          <div className="flex items-center bg-astro-bg-primary border border-astro-border-hairline rounded-sm p-0.5 font-mono text-[10px]">
            <button
              onClick={() => onModeChange('DETERMINISTIC_FALLBACK')}
              className={`px-2 py-0.5 rounded-sm transition-all ${
                isFallback
                  ? 'bg-astro-sage/20 text-astro-text-primary font-bold'
                  : 'text-astro-text-secondary hover:text-astro-text-primary'
              }`}
            >
              Fallback Mode
            </button>
            <button
              onClick={() => onModeChange('GEMINI_LIVE')}
              className={`px-2 py-0.5 rounded-sm transition-all flex items-center space-x-1 ${
                !isFallback
                  ? 'bg-astro-sage/20 text-astro-text-primary font-bold'
                  : 'text-astro-text-secondary hover:text-astro-text-primary'
              }`}
            >
              <Sparkles className="w-2.5 h-2.5" />
              <span>Gemini Proxy</span>
            </button>
          </div>

          <button
            onClick={onRefresh}
            disabled={isLoading}
            className="p-1.5 border border-astro-border-hairline rounded-sm hover:bg-astro-bg-subtle text-astro-text-secondary hover:text-astro-text-primary transition-all disabled:opacity-50"
            title="Refresh AI Analysis"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin text-astro-sage' : ''}`} />
          </button>
        </div>
      </div>

      {/* Metric Counters Strip */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 pt-1 border-t border-astro-border-hairline/60 font-mono text-[10px]">
        <div>
          <span className="text-astro-text-secondary block">RECORDS ANALYZED</span>
          <span className="font-bold text-astro-text-primary text-xs">{overview.analyzedRecordsCount}</span>
        </div>
        <div>
          <span className="text-astro-text-secondary block">ANOMALIES REVIEWED</span>
          <span className="font-bold text-astro-text-primary text-xs">{overview.anomaliesReviewedCount}</span>
        </div>
        <div>
          <span className="text-astro-text-secondary block">ACTIVE CHANNELS</span>
          <span className="font-bold text-astro-sage text-xs">7 MONITORED</span>
        </div>
        <div>
          <span className="text-astro-text-secondary block">LAST SYNTHESIS</span>
          <span className="text-astro-text-primary text-[10px]">
            {overview.latestAnalysisTimestamp
              ? new Date(overview.latestAnalysisTimestamp).toLocaleTimeString()
              : 'INITIALIZING'}
          </span>
        </div>
      </div>
    </div>
  );
};
