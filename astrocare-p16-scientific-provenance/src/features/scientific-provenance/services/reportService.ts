import { ScientificClaim } from '../types/claim.types'
import { ScientificSource } from '../types/source.types'
import { EvidenceRecord } from '../types/evidence.types'
import { ResearchReportConfig, GeneratedReport } from '../types/report.types'
import { CitationService } from './citationService'

export class ReportService {
  /**
   * Generates a comprehensive research transparency report
   */
  public static generateReport(
    config: ResearchReportConfig,
    claims: ScientificClaim[],
    sources: ScientificSource[],
    evidenceList: EvidenceRecord[]
  ): GeneratedReport {
    const selectedClaims = claims.filter((c) => config.includedClaimIds.includes(c.id))
    const reportId = `REP-${Date.now().toString(36).toUpperCase()}`
    const generatedAt = new Date().toISOString()

    const sourceMap = new Map<string, ScientificSource>(sources.map((s) => [s.id, s]))
    const evidenceMap = new Map<string, EvidenceRecord>(evidenceList.map((e) => [e.id, e]))

    const referencedSourceIds = new Set<string>()
    let missingSourceWarningCount = 0

    selectedClaims.forEach((c) => {
      if (c.sourceIds.length === 0) {
        missingSourceWarningCount++
      }
      c.sourceIds.forEach((id) => referencedSourceIds.add(id))
    })

    const referencedSources = Array.from(referencedSourceIds)
      .map((id) => sourceMap.get(id))
      .filter((s): s is ScientificSource => !!s)

    // Build Markdown document
    let md = `# ASTROCARE SCIENTIFIC PROVENANCE & RESEARCH TRANSPARENCY REPORT\n\n`
    md += `**Report Title:** ${config.title}\n`
    md += `**Generated At:** ${generatedAt} (UTC)\n`
    md += `**Generated By:** ${config.generatedBy}\n`
    md += `**Claims Analyzed:** ${selectedClaims.length} | **Supporting Sources:** ${referencedSources.length} | **Missing Source Warnings:** ${missingSourceWarningCount}\n\n`
    md += `---\n\n`

    if (missingSourceWarningCount > 0 && config.includeMissingSourceWarnings) {
      md += `> [!WARNING]\n`
      md += `> **UNVERIFIED SCIENTIFIC CLAIMS DETECTED:** ${missingSourceWarningCount} claim(s) in this report have no linked authentic scientific sources. In accordance with AstroCare Scientific Integrity Standards, these statements must not be presented as established facts.\n\n`
    }

    md += `## 1. SCIENTIFIC CLAIMS & EVIDENCE TRACEABILITY MATRIX\n\n`

    selectedClaims.forEach((claim, idx) => {
      md += `### ${idx + 1}. Claim [${claim.id}] — Status: **${claim.claimStatus.toUpperCase().replace('_', ' ')}**\n\n`
      md += `**Statement:** "${claim.claimText}"\n\n`
      md += `- **Research Domain:** \`${claim.researchDomain}\`\n`
      md += `- **Claim Category:** \`${claim.claimCategory}\`\n`
      md += `- **Last Reviewed:** ${claim.lastReviewed}\n`

      if (claim.sourceIds.length === 0) {
        md += `- **Supporting Sources:** *None registered. (Warning: Missing Source)*\n\n`
      } else {
        md += `- **Supporting Sources:** ${claim.sourceIds.join(', ')}\n\n`
      }

      if (config.includeStudyPopulations && claim.studyPopulation) {
        md += `**Study Population / Model:**\n${claim.studyPopulation}\n\n`
      }

      if (config.includeMethodology && claim.researchMethodology) {
        md += `**Research Methodology:**\n${claim.researchMethodology}\n\n`
      }

      if (config.includeLimitations && claim.limitations) {
        md += `**Known Scientific Limitations:**\n${claim.limitations}\n\n`
      }

      if (config.includeEvidenceClassifications && claim.evidenceIds.length > 0) {
        md += `#### Supporting Evidence Records for [${claim.id}]:\n\n`
        md += `| Evidence ID | Study Type | Organism / Cohort | Supporting Relationship | Findings Excerpt |\n`
        md += `| :--- | :--- | :--- | :--- | :--- |\n`

        claim.evidenceIds.forEach((eid) => {
          const ev = evidenceMap.get(eid)
          if (ev) {
            const shortFinding = ev.keyFindings.replace(/\|/g, '\\|').slice(0, 100) + '...'
            md += `| \`${ev.id}\` | \`${ev.studyType}\` | ${ev.organism} | \`${ev.supportingRelationship}\` | ${shortFinding} |\n`
          }
        })
        md += `\n`
      }

      md += `---\n\n`
    })

    if (config.includeCitationList && referencedSources.length > 0) {
      md += `## 2. FORMATTED SCIENTIFIC BIBLIOGRAPHY (${config.citationStyle.toUpperCase()} FORMAT)\n\n`
      referencedSources.forEach((s, i) => {
        const citation = CitationService.formatCitation(s, config.citationStyle)
        md += `${i + 1}. ${citation.formattedText}\n`
        if (!citation.isComplete) {
          md += `   *(Incomplete Metadata Notice: Missing ${citation.missingFields.join(', ')})*\n`
        }
        md += `\n`
      })
    }

    md += `\n---\n*Report generated by AstroCare P16 Scientific Provenance Engine. Validated against official NASA Human Research Roadmap and Open Science Data Repositories.*`

    const jsonExport = {
      reportId,
      title: config.title,
      generatedAt,
      generatedBy: config.generatedBy,
      citationStyle: config.citationStyle,
      metrics: {
        claimCount: selectedClaims.length,
        sourceCount: referencedSources.length,
        missingSourceWarningCount,
      },
      claims: selectedClaims.map((c) => ({
        ...c,
        supportingSources: c.sourceIds.map((sid) => sourceMap.get(sid)).filter(Boolean),
        evidenceRecords: c.evidenceIds.map((eid) => evidenceMap.get(eid)).filter(Boolean),
      })),
      bibliography: referencedSources.map((s) =>
        CitationService.formatCitation(s, config.citationStyle)
      ),
    }

    return {
      id: reportId,
      title: config.title,
      generatedAt,
      generatedBy: config.generatedBy,
      claimCount: selectedClaims.length,
      sourceCount: referencedSources.length,
      evidenceCount: selectedClaims.reduce((sum, c) => sum + c.evidenceIds.length, 0),
      missingSourceWarningCount,
      markdownContent: md,
      jsonExport,
    }
  }

  /**
   * Generates CSV export for claims and evidence matrix
   */
  public static exportCSV(
    claims: ScientificClaim[],
    sources: ScientificSource[],
    evidence: EvidenceRecord[]
  ): string {
    const sourceMap = new Map(sources.map((s) => [s.id, s]))
    const evMap = new Map(evidence.map((e) => [e.id, e]))

    const headers = [
      'Claim ID',
      'Status',
      'Domain',
      'Claim Statement',
      'Supporting Source IDs',
      'Primary Source Title',
      'Source Type',
      'Evidence ID',
      'Study Type',
      'Organism',
      'Supporting Relationship',
      'Last Reviewed',
    ]

    const rows: string[][] = []

    claims.forEach((claim) => {
      if (claim.evidenceIds.length === 0) {
        const firstSource = claim.sourceIds[0] ? sourceMap.get(claim.sourceIds[0]) : null
        rows.push([
          claim.id,
          claim.claimStatus,
          claim.researchDomain,
          `"${claim.claimText.replace(/"/g, '""')}"`,
          claim.sourceIds.join('; '),
          firstSource ? `"${firstSource.title.replace(/"/g, '""')}"` : 'None',
          firstSource?.sourceType || 'None',
          'None',
          'None',
          'None',
          'None',
          claim.lastReviewed,
        ])
      } else {
        claim.evidenceIds.forEach((eid) => {
          const ev = evMap.get(eid)
          const src = ev ? sourceMap.get(ev.sourceId) : null
          rows.push([
            claim.id,
            claim.claimStatus,
            claim.researchDomain,
            `"${claim.claimText.replace(/"/g, '""')}"`,
            claim.sourceIds.join('; '),
            src ? `"${src.title.replace(/"/g, '""')}"` : 'None',
            src?.sourceType || 'None',
            ev ? ev.id : 'None',
            ev ? ev.studyType : 'None',
            ev ? ev.organism : 'None',
            ev ? ev.supportingRelationship : 'None',
            claim.lastReviewed,
          ])
        })
      }
    })

    return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n')
  }
}
